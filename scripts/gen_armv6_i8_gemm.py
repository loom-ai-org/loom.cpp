# ADR-079 P4.33 step 2: generates the ARMv6 int8 GEMM tiles, ADR-077 gate 2's tile2x4_k256 generalized to
# any K. 2 columns x 4 output channels, int16 operand pairs, SMLAD, P K-pairs fully unrolled with
# immediate offsets; the accumulators live in memory between calls, so a K of any multiple of 32 runs as
# chunks of 128 pairs and then 16.
#   void ggml_armv6_i8_tile_p<P>(const uint32_t * x, const uint32_t * w, int32_t * acc)
#   x:   [P][2] words, pair k of column 0 then of column 1 (each word two int16 in k order)
#   w:   [P][4] words, pair k of channels 0..3
#   acc: int32[8] in and out: column 0's four channels, then column 1's
# x is prefetched 128 bytes ahead, one PLD per 32 B line: an x line from the Pi Zero's L2 costs ~100 cycles,
# as much as one from DRAM, and the PLD took a tile with x from L2 from 0.78 to 1.45 GOP/s (bench61.c;
# 64 / 128 / 256 bytes ahead measured the same).
# Registers: accumulators r2-r9 (r2 is the acc pointer, pushed, then loaded over), x0/x1 = r10/r11,
# wA/wB = r12/lr. 14 instructions per K pair: 8 SMLADs and 6 loads, every load consumed at least 3
# instructions later (the ARM1176's load-use latency), as in gen_armv6_i8_tile.py.
#   python3 scripts/gen_armv6_i8_gemm.py out.S            (assembly file)
#   python3 scripts/gen_armv6_i8_gemm.py out.inc --inc    (a C string for a top-level __asm__)
#   --pld adds bench61.c's variants: _nopld, _pld64, _pld256
import sys

c0 = ["r2", "r3", "r4", "r5"]
c1 = ["r6", "r7", "r8", "r9"]


def tile(P, pld=128, suffix=""):
    L = []
    e = L.append
    name = f"ggml_armv6_i8_tile_p{P}{suffix}"
    e(f"    .text\n    .arm\n    .align 4\n    .global {name}\n    .type {name}, %function\n{name}:")
    e("    push {r2, r4-r11, lr}")
    e("    ldmia r2, {r2-r9}")
    e("    ldr r10, [r0]")
    e("    ldr r11, [r0, #4]")
    e("    ldr r12, [r1]")
    e("    ldr lr, [r1, #4]")
    for k in range(P):
        last = k == P - 1
        w, x = 16 * k, 8 * k

        def mac(acc, a, b):
            e(f"    smlad {acc}, {a}, {b}, {acc}")

        mac(c0[0], "r10", "r12")
        if pld and k % 4 == 0:   # one PLD per 32 B line of x (four pairs), `pld` bytes ahead
            e(f"    pld [r0, #{x + pld}]")
        mac(c1[0], "r11", "r12")
        e(f"    ldr r12, [r1, #{w + 8}]")
        mac(c0[1], "r10", "lr"); mac(c1[1], "r11", "lr")
        e(f"    ldr lr, [r1, #{w + 12}]")
        mac(c0[2], "r10", "r12"); mac(c1[2], "r11", "r12")
        if not last:
            e(f"    ldr r12, [r1, #{w + 16}]")
        mac(c0[3], "r10", "lr")
        if not last:
            e(f"    ldr r10, [r0, #{x + 8}]")
        mac(c1[3], "r11", "lr")
        if not last:
            e(f"    ldr r11, [r0, #{x + 12}]")
            e(f"    ldr lr, [r1, #{w + 20}]")
    e("    pop {r10}")
    e("    stmia r10, {r2-r9}")
    e("    pop {r4-r11, pc}")
    e(f"    .size {name}, .-{name}")
    return L


def main():
    L = tile(128) + tile(16)
    if "--pld" in sys.argv:   # bench61's variants: x not prefetched, or 64 / 256 bytes ahead
        L += tile(128, 0, "_nopld") + tile(16, 0, "_nopld")
        for d in (64, 256):
            L += tile(128, d, f"_pld{d}") + tile(16, d, f"_pld{d}")
    if "--inc" in sys.argv:   # a header ggml includes at file scope (arch/arm/armv6-i8-gemm.inc)
        body = "".join(f'    "{line}\\n"\n' for line in "\n".join(L).split("\n"))
        decls = "".join(f"extern \"C\" void {n}(const uint32_t * x, const uint32_t * w, int32_t * acc);\n"
                        for n in (l.split()[-1] for l in "\n".join(L).split("\n") if l.strip().startswith(".global")))
        text = ("// GENERATED by loom.cpp scripts/gen_armv6_i8_gemm.py (ADR-079 P4.33) -- edit the generator, not this.\n"
                "// ARMv6 only: the int8 GEMM tiles of armv6-i8.cpp, 2 columns x 4 channels, int16 pairs, SMLAD.\n"
                "#pragma once\n#include <stdint.h>\n\n__asm__(\n" + body + ");\n\n" + decls)
    else:
        text = "\n".join(L) + '\n    .section .note.GNU-stack,"",%progbits\n'
    with open(sys.argv[1], "w") as f:
        f.write(text)


main()
